"""Compile the writer's Markdown + Pandas statistics into a styled A4 PDF with ReportLab."""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime
from functools import partial
from pathlib import Path
from xml.sax.saxutils import escape

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.enums import TA_JUSTIFY, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    ListFlowable,
    ListItem,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from crew.analysis import compute_summary_statistics

NAVY = colors.HexColor("#1F3A5F")
ACCENT = colors.HexColor("#2E86AB")
LIGHT = colors.HexColor("#F2F5F9")
GREY = colors.HexColor("#6B7280")
RULE = colors.HexColor("#D1D5DB")

PAGE_W, PAGE_H = A4
MARGIN = 18 * mm
BANNER_H = 22 * mm
CONTENT_W = PAGE_W - 2 * MARGIN


@dataclass
class ReportMetadata:
    title: str = "Market Research Report"
    query: str = ""
    author: str = "Market Research Crew (CrewAI)"
    generated_at: str = field(default_factory=lambda: datetime.now().strftime("%Y-%m-%d %H:%M"))
    footer_note: str = "Generated by a multi-agent CrewAI pipeline. For information purposes only; not investment advice."


# --------------------------------------------------------------------------
# Canvas with header banner and "Page X of Y" footer (two-pass numbering)
# --------------------------------------------------------------------------
class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, metadata: ReportMetadata | None = None, **kwargs):
        super().__init__(*args, **kwargs)
        self.metadata = metadata or ReportMetadata()
        self._saved_page_states: list[dict] = []

    def showPage(self):  # noqa: N802 (ReportLab API)
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_chrome(total)
            super().showPage()
        super().save()

    def _draw_chrome(self, total_pages: int) -> None:
        m = self.metadata
        self.saveState()
        # banner
        self.setFillColor(NAVY)
        self.rect(0, PAGE_H - BANNER_H, PAGE_W, BANNER_H, stroke=0, fill=1)
        self.setFillColor(ACCENT)
        self.rect(0, PAGE_H - BANNER_H - 1.2 * mm, PAGE_W, 1.2 * mm, stroke=0, fill=1)
        self.setFillColor(colors.white)
        self.setFont("Helvetica-Bold", 15)
        self.drawString(MARGIN, PAGE_H - 11 * mm, m.title[:60])
        self.setFont("Helvetica", 8.5)
        self.drawString(MARGIN, PAGE_H - 17 * mm, f"Query: {m.query[:70]}")
        self.drawRightString(PAGE_W - MARGIN, PAGE_H - 17 * mm, f"Generated: {m.generated_at}")
        # footer
        self.setStrokeColor(RULE)
        self.setLineWidth(0.6)
        self.line(MARGIN, 16 * mm, PAGE_W - MARGIN, 16 * mm)
        self.setFillColor(GREY)
        self.setFont("Helvetica", 7.5)
        self.drawString(MARGIN, 11 * mm, m.footer_note[:120])
        self.setFont("Helvetica-Bold", 8)
        self.drawRightString(PAGE_W - MARGIN, 11 * mm, f"Page {self._pageNumber} of {total_pages}")
        self.restoreState()


# --------------------------------------------------------------------------
# Styles
# --------------------------------------------------------------------------
def build_styles() -> dict[str, ParagraphStyle]:
    base = dict(fontName="Helvetica", textColor=colors.HexColor("#111827"))
    return {
        "body": ParagraphStyle("body", fontSize=10, leading=14.5, alignment=TA_JUSTIFY, spaceAfter=6, **base),
        "h1": ParagraphStyle("h1", fontName="Helvetica-Bold", fontSize=17, leading=21, textColor=NAVY,
                             spaceBefore=4, spaceAfter=8, keepWithNext=1),
        "h2": ParagraphStyle("h2", fontName="Helvetica-Bold", fontSize=13, leading=17, textColor=NAVY,
                             spaceBefore=12, spaceAfter=5, keepWithNext=1),
        "h3": ParagraphStyle("h3", fontName="Helvetica-Bold", fontSize=11, leading=15, textColor=ACCENT,
                             spaceBefore=8, spaceAfter=3, keepWithNext=1),
        "cell": ParagraphStyle("cell", fontSize=8.5, leading=11, **base),
        "cell_right": ParagraphStyle("cell_right", fontSize=8.5, leading=11, alignment=TA_RIGHT, **base),
        "cell_head": ParagraphStyle("cell_head", fontName="Helvetica-Bold", fontSize=8.5, leading=11,
                                    textColor=colors.white),
        "note": ParagraphStyle("note", fontSize=8, leading=11, textColor=GREY, fontName="Helvetica-Oblique",
                               spaceBefore=3, spaceAfter=6),
    }


# --------------------------------------------------------------------------
# Markdown -> ReportLab flowables
# --------------------------------------------------------------------------
_LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")
_BOLD = re.compile(r"\*\*(.+?)\*\*")
_ITALIC = re.compile(r"(?<![\*\w])\*(?!\s)(.+?)(?<!\s)\*(?![\*\w])")
_CODE = re.compile(r"`([^`]+)`")


def inline_markup(text: str) -> str:
    """Escape XML special characters, then convert inline Markdown to ReportLab markup."""
    text = escape(text)
    text = _LINK.sub(r'<a href="\2" color="#2E86AB">\1</a>', text)
    text = _BOLD.sub(r"<b>\1</b>", text)
    text = _ITALIC.sub(r"<i>\1</i>", text)
    text = _CODE.sub(r'<font face="Courier">\1</font>', text)
    return text


def make_table(header: list[str], rows: list[list[str]], styles: dict, numeric_from: int | None = None,
               first_col_weight: float = 1.6) -> Table:
    """Build a styled, wrap-safe table that fits the A4 content width."""
    ncols = len(header)
    weights = [first_col_weight] + [1.0] * (ncols - 1) if ncols > 1 else [1.0]
    widths = [CONTENT_W * w / sum(weights) for w in weights]

    def cell(value: str, col: int) -> Paragraph:
        right = numeric_from is not None and col >= numeric_from
        return Paragraph(inline_markup(str(value)), styles["cell_right" if right else "cell"])

    data = [[Paragraph(inline_markup(str(h)), styles["cell_head"]) for h in header]]
    for row in rows:
        row = (list(row) + [""] * ncols)[:ncols]
        data.append([cell(v, i) for i, v in enumerate(row)])

    table = Table(data, colWidths=widths, repeatRows=1, hAlign="LEFT")
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
        ("GRID", (0, 0), (-1, -1), 0.4, RULE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
    ]))
    return table


def _parse_table_lines(lines: list[str]) -> tuple[list[str], list[list[str]]]:
    rows = [[c.strip() for c in ln.strip().strip("|").split("|")] for ln in lines]
    rows = [r for r in rows if not all(re.fullmatch(r":?-{2,}:?", c) for c in r)]  # drop |---|---| separator
    header, body = rows[0], rows[1:]
    return header, body


def markdown_to_flowables(md: str, styles: dict) -> list:
    """Convert the writer's Markdown (headings, paragraphs, lists, tables, rules) to flowables."""
    flow: list = []
    para: list[str] = []
    items: list[str] = []
    ordered = False

    def flush_para():
        if para:
            flow.append(Paragraph(inline_markup(" ".join(para)), styles["body"]))
            para.clear()

    def flush_list():
        nonlocal ordered
        if items:
            li = [ListItem(Paragraph(inline_markup(t), styles["body"]), leftIndent=14) for t in items]
            if ordered:
                flow.append(ListFlowable(li, bulletType="1", bulletFormat="%s.", leftIndent=14))
            else:
                flow.append(ListFlowable(li, bulletType="bullet", start="\u2022", leftIndent=14))
            items.clear()
        ordered = False

    lines = md.splitlines()
    i = 0
    while i < len(lines):
        stripped = lines[i].strip()
        if not stripped:
            flush_para(); flush_list(); i += 1; continue

        heading = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if heading:
            flush_para(); flush_list()
            level = min(len(heading.group(1)), 3)
            flow.append(Paragraph(inline_markup(heading.group(2)), styles[f"h{level}"]))
            i += 1; continue

        if stripped.startswith("|"):
            flush_para(); flush_list()
            block = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                block.append(lines[i]); i += 1
            header, body = _parse_table_lines(block)
            flow.append(make_table(header, body, styles))
            flow.append(Spacer(1, 8))
            continue

        if re.fullmatch(r"(-{3,}|\*{3,}|_{3,})", stripped):
            flush_para(); flush_list()
            flow.append(HRFlowable(width="100%", thickness=0.6, color=RULE, spaceBefore=4, spaceAfter=6))
            i += 1; continue

        bullet = re.match(r"^([-*+]|\d+[.)])\s+(.*)$", stripped)
        if bullet:
            flush_para()
            is_ordered = bullet.group(1)[0].isdigit()
            if items and is_ordered != ordered:
                flush_list()
            ordered = is_ordered
            items.append(bullet.group(2))
            i += 1; continue

        flush_list()
        para.append(stripped)
        i += 1

    flush_para(); flush_list()
    return flow


# --------------------------------------------------------------------------
# Statistics / dataset sections
# --------------------------------------------------------------------------
def _fmt(value) -> str:
    """Format numbers with thousands separators and 2 decimals; NaN becomes an em dash."""
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "\u2014"
    try:
        return f"{float(value):,.2f}"
    except (TypeError, ValueError):
        return str(value)


def stats_section(summary_df: pd.DataFrame, styles: dict) -> list:
    """Heading + grid table rendering the Pandas summary statistics (metrics as rows, stats as columns)."""
    transposed = summary_df.T
    header = ["Metric"] + [str(c).capitalize() for c in transposed.columns]
    rows = []
    for metric, row in transposed.iterrows():
        cells = [str(metric)]
        for stat, val in row.items():
            cells.append(f"{int(val)}" if stat == "count" and pd.notna(val) else _fmt(val))
        rows.append(cells)
    return [KeepTogether([
        Paragraph("Financial Metrics Summary", styles["h2"]),
        Paragraph("Summary statistics computed with Pandas from the collected dataset.", styles["note"]),
        make_table(header, rows, styles, numeric_from=1),
    ])]


def dataset_section(df: pd.DataFrame, styles: dict, max_rows: int = 15) -> list:
    """Optional appendix with the first rows of the underlying dataset."""
    shown = df.head(max_rows)
    header = [str(c) for c in shown.columns]
    rows = [[_fmt(v) if isinstance(v, float) else str(v) for v in r] for r in shown.itertuples(index=False)]
    note = f"Showing {len(shown)} of {len(df)} rows." if len(df) > max_rows else f"{len(df)} rows."
    return [
        Paragraph("Underlying Dataset", styles["h2"]),
        Paragraph(note, styles["note"]),
        make_table(header, rows, styles, numeric_from=1),
    ]


# --------------------------------------------------------------------------
# Public API
# --------------------------------------------------------------------------
def build_pdf_report(markdown_text: str, summary_df: pd.DataFrame, output_path: str | Path,
                     metadata: ReportMetadata | None = None, raw_df: pd.DataFrame | None = None) -> Path:
    """Write the A4 PDF report and return its path."""
    if not markdown_text or not markdown_text.strip():
        raise ValueError("Report markdown is empty; nothing to compile.")
    metadata = metadata or ReportMetadata()
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    styles = build_styles()

    story = markdown_to_flowables(markdown_text, styles)
    story.append(Spacer(1, 10))
    story += stats_section(summary_df, styles)
    if raw_df is not None:
        story.append(Spacer(1, 6))
        story += dataset_section(raw_df, styles)

    doc = SimpleDocTemplate(
        str(output_path), pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN, topMargin=BANNER_H + 12 * mm, bottomMargin=22 * mm,
        title=metadata.title, author=metadata.author, subject=metadata.query or "Market research report",
        canvasmaker=partial(NumberedCanvas, metadata=metadata),
    )
    doc.build(story)
    return output_path


def generate_report(markdown_text: str, csv_path: str | Path, output_path: str | Path, query: str = "") -> Path:
    """Convenience wrapper: load CSV, compute statistics with Pandas and compile the PDF."""
    from crew.analysis import load_metrics

    df = load_metrics(csv_path)
    title_match = re.search(r"^#\s+(.+)$", markdown_text, flags=re.MULTILINE)
    meta = ReportMetadata(title=title_match.group(1).strip() if title_match else (query or "Market Research Report"),
                          query=query)
    return build_pdf_report(markdown_text, compute_summary_statistics(df), output_path, meta, raw_df=df)
